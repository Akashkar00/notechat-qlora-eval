"""Cross-arm comparison (PROJECT_SPEC.md §5 Phase 2 "paired bootstrap").

Reads every `artifacts/eval/*/results.json`, checks the arms are actually
comparable, and computes paired bootstrap deltas between them. Exists
because `PROJECT_SPEC.md` §1.2 requires every reported number to be
reproducible by a single documented command — the comparison numbers in
README.md were previously produced by an ad-hoc script, which made them the
one set of figures in the repo that nobody else could regenerate.

Run:
    python -m src.eval.compare
    python -m src.eval.compare --arms finetuned zero-shot-14b

Writes `artifacts/eval/comparison.json` (machine-readable, every pairing)
and `artifacts/eval/comparison.md` (the table that goes in README.md).
"""

import argparse
import itertools
import json
from pathlib import Path

import yaml

from src.eval.metrics import paired_bootstrap_delta

EVAL_CONFIG_PATH = Path("configs/eval.yaml")
RESULTS_DIR = Path("artifacts/eval")

COMPARED_METRICS = [
    "rouge1",
    "rouge2",
    "rougeL",
    "bertscore_f1",
    "numeric_grounding_recall",
    "fabricated_number_rate",
]


def load_arms(arm_names: list[str] | None = None) -> dict[str, dict]:
    """Load each arm's results.json, keyed by arm name."""
    arms = {}
    for results_path in sorted(RESULTS_DIR.glob("*/results.json")):
        result = json.loads(results_path.read_text())
        name = result.get("arm", results_path.parent.name)
        if arm_names is None or name in arm_names:
            arms[name] = result
    if not arms:
        raise FileNotFoundError(
            f"No results found under {RESULTS_DIR}/*/results.json — run `python -m src.eval.run_eval` first."
        )
    return arms


def assert_comparable(arms: dict[str, dict]) -> list[str]:
    """Fail loudly if the arms aren't scored on the same records.

    A paired bootstrap is only meaningful over identical, index-aligned
    records. Silently intersecting mismatched runs would produce a
    confident-looking delta computed on whatever happened to overlap —
    exactly the kind of quiet wrongness PROJECT_SPEC.md §6 says to prefer
    failing over.
    """
    id_sets = {name: {r["note_id"] for r in result["records"]} for name, result in arms.items()}
    reference_name, reference_ids = next(iter(id_sets.items()))
    for name, ids in id_sets.items():
        if ids != reference_ids:
            only_here = len(ids - reference_ids)
            only_there = len(reference_ids - ids)
            raise ValueError(
                f"Arm '{name}' was not scored on the same records as '{reference_name}' "
                f"({only_here} records only in '{name}', {only_there} only in '{reference_name}'). "
                f"Re-run both with the same --n-records and --seed before comparing."
            )

    sampled = {name: result.get("decoding", {}).get("do_sample", False) for name, result in arms.items()}
    if any(sampled.values()):
        stochastic = [name for name, is_sampled in sampled.items() if is_sampled]
        print(
            f"WARNING: arm(s) {stochastic} used stochastic decoding. Their scores are one draw "
            f"from a distribution, so the intervals below understate true uncertainty. "
            f"Re-run without --sample for reproducible numbers."
        )
    return sorted(reference_ids)


def compare_pair(arms: dict[str, dict], a_name: str, b_name: str, bs_cfg: dict) -> dict:
    """Paired bootstrap delta (a − b) on every metric both arms recorded."""
    a_by_id = {r["note_id"]: r for r in arms[a_name]["records"]}
    b_by_id = {r["note_id"]: r for r in arms[b_name]["records"]}
    note_ids = sorted(a_by_id)

    deltas = {}
    for metric in COMPARED_METRICS:
        if metric not in a_by_id[note_ids[0]] or metric not in b_by_id[note_ids[0]]:
            continue  # arm predates this metric; skip rather than crash
        delta = paired_bootstrap_delta(
            [a_by_id[nid][metric] for nid in note_ids],
            [b_by_id[nid][metric] for nid in note_ids],
            n_resamples=bs_cfg["n_resamples"],
            confidence_level=bs_cfg["confidence_level"],
        )
        # A CI excluding zero is the whole point of running this; precompute
        # it so no downstream reader has to eyeball two floats to decide.
        delta["excludes_zero"] = delta["ci_low"] > 0 or delta["ci_high"] < 0
        deltas[metric] = delta
    return deltas


def render_markdown(arms: dict[str, dict], comparisons: dict) -> str:
    lines = [
        "# Cross-arm comparison",
        "",
        "Generated by `python -m src.eval.compare`. Do not hand-edit.",
        "",
        "## Per-arm point estimates (95% percentile bootstrap CI)",
        "",
        "| Arm | ROUGE-1 | ROUGE-L | BERTScore-F1 | Numeric grounding | Fabricated numbers | Turn-format valid |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, result in sorted(arms.items()):
        agg = result["aggregate"]

        def ci(metric: str) -> str:
            if metric not in agg:
                return "—"
            m = agg[metric]
            return f"{m['point_estimate']:.3f} [{m['ci_low']:.3f}, {m['ci_high']:.3f}]"

        lines.append(
            f"| {name} | {ci('rouge1')} | {ci('rougeL')} | {ci('bertscore_f1')} | "
            f"{ci('numeric_grounding_recall')} | {ci('fabricated_number_rate')} | "
            f"{agg['turn_format_valid_rate']:.1%} |"
        )

    lines += ["", "## Paired bootstrap deltas", ""]
    for pair_name, deltas in comparisons.items():
        a_name, b_name = pair_name.split(" vs ")
        lines += [
            f"### {a_name} − {b_name}",
            "",
            "| Metric | Δ | 95% CI | Excludes zero |",
            "|---|---|---|---|",
        ]
        for metric, d in deltas.items():
            lines.append(
                f"| {metric} | {d['delta']:+.4f} | [{d['ci_low']:+.4f}, {d['ci_high']:+.4f}] | "
                f"{'yes' if d['excludes_zero'] else 'NO'} |"
            )
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--arms", nargs="*", default=None, help="Arm names to compare (default: all found)")
    args = parser.parse_args()

    bs_cfg = yaml.safe_load(EVAL_CONFIG_PATH.read_text())["bootstrap"]
    arms = load_arms(args.arms)
    note_ids = assert_comparable(arms)
    print(f"Comparing {len(arms)} arms on {len(note_ids)} shared records: {', '.join(sorted(arms))}")

    comparisons = {
        f"{a} vs {b}": compare_pair(arms, a, b, bs_cfg) for a, b in itertools.combinations(sorted(arms), 2)
    }

    payload = {
        "n_records": len(note_ids),
        "arms": {name: result["aggregate"] for name, result in arms.items()},
        "comparisons": comparisons,
    }
    # Explicit UTF-8: Windows defaults to cp1252, which cannot encode the
    # minus sign / en dash this report uses and fails the whole run at the
    # very last step.
    (RESULTS_DIR / "comparison.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    (RESULTS_DIR / "comparison.md").write_text(render_markdown(arms, comparisons), encoding="utf-8")
    print(f"Wrote {RESULTS_DIR / 'comparison.json'} and {RESULTS_DIR / 'comparison.md'}")


if __name__ == "__main__":
    main()
